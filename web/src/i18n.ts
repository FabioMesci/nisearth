// Idioma de la interfaz (ES/EN). Los textos de cada caso están en content.ts.
export type Lang = 'es' | 'en'

const KEY = 'lang'
const read = (): Lang => {
  try {
    const v = localStorage.getItem(KEY)
    if (v === 'es' || v === 'en') return v
  } catch {
    /* almacenamiento no disponible */
  }
  return navigator.language?.toLowerCase().startsWith('es') ? 'es' : 'en'
}

export let lang: Lang = read()
const listeners: (() => void)[] = []

export function setLang(l: Lang) {
  lang = l
  try {
    localStorage.setItem(KEY, l)
  } catch {
    /* sin persistencia */
  }
  document.documentElement.lang = l
  listeners.forEach((f) => f())
}
export const onLang = (f: () => void) => listeners.push(f)

export const locale = () => (lang === 'es' ? 'es-ES' : 'en-GB')
/** Fechas de adquisición ('2026-10-23'): se interpretan y se muestran en UTC.
 *  Sin timeZone, un visitante en América vería el día anterior. */
/** Número con decimales fijos en el formato del idioma (0,63 en español, 0.63 en inglés) */
export const fmtDec = (v: number | string, d = 2) => (+v).toLocaleString(locale(), { minimumFractionDigits: d, maximumFractionDigits: d })

export const fmtDay = (d: string, opts: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'short' }) =>
  new Date(d).toLocaleDateString(locale(), { ...opts, timeZone: 'UTC' })

